-- UNIFIED SEARCH INDEX
CREATE VIRTUAL TABLE IF NOT EXISTS SEARCH_INDEX_FTS5 USING fts5(
    REGION,          -- 'EU', 'AM', 'ASIA'
    TABLE_TYPE,      -- 'DEATHMATCH', 'CLAN'
    SEARCH_TEXT,     -- NICKNAME or TAG
    SEASON_ID,
    REFERENCE_KEY,    -- For Deathmatch: 'ID|SEASON_ID', For Clan: 'TAG|SEASON_ID'
    tokenize = "trigram"
);

-- Triggers for EU Deathmatch
CREATE TRIGGER IF NOT EXISTS EU_DEATHMATCH_RANKING_INSERT_TRIGGER AFTER INSERT ON EU_DEATHMATCH_RANKING
BEGIN
    INSERT INTO SEARCH_INDEX_FTS5 (REGION, TABLE_TYPE, SEARCH_TEXT, SEASON_ID, REFERENCE_KEY)
    VALUES ('EU', 'DEATHMATCH', new.NICKNAME, new.SEASON_ID, new.ID || '|' || new.SEASON_ID);
END;

CREATE TRIGGER IF NOT EXISTS EU_DEATHMATCH_RANKING_UPDATE_TRIGGER AFTER UPDATE ON EU_DEATHMATCH_RANKING
BEGIN
    DELETE FROM SEARCH_INDEX_FTS5 WHERE REFERENCE_KEY = old.ID || '|' || old.SEASON_ID AND REGION = 'EU' AND TABLE_TYPE = 'DEATHMATCH';
    INSERT INTO SEARCH_INDEX_FTS5 (REGION, TABLE_TYPE, SEARCH_TEXT, SEASON_ID, REFERENCE_KEY)
    VALUES ('EU', 'DEATHMATCH', new.NICKNAME, new.SEASON_ID, new.ID || '|' || new.SEASON_ID);
END;

CREATE TRIGGER IF NOT EXISTS EU_DEATHMATCH_RANKING_DELETE_TRIGGER AFTER DELETE ON EU_DEATHMATCH_RANKING
BEGIN
    DELETE FROM SEARCH_INDEX_FTS5 WHERE REFERENCE_KEY = old.ID || '|' || old.SEASON_ID AND REGION = 'EU' AND TABLE_TYPE = 'DEATHMATCH';
END;

