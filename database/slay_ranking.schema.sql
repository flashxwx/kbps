PRAGMA journal_mode=WAL;
PRAGMA synchronous=NORMAL;
PRAGMA busy_timeout=5000;

-- EU SERVER
CREATE TABLE IF NOT EXISTS EU_DEATHMATCH_RANKING (
    ID INTEGER NOT NULL,
    SEASON_ID TEXT NOT NULL,
    NICKNAME TEXT NOT NULL,
    CLAN_TAG TEXT DEFAULT '',
    KILLS INTEGER DEFAULT 0,
    BOT_KILLS INTEGER DEFAULT 0,
    ELO REAL DEFAULT 1000,
    LOGS TEXT DEFAULT '',
    MATCH_PLAYED_COUNT INTEGER DEFAULT 0,
    PRIMARY KEY (ID, SEASON_ID)
);

CREATE INDEX IF NOT EXISTS INDEX_OF_EU_DEATHMATCH_KILLS ON EU_DEATHMATCH_RANKING(SEASON_ID, KILLS DESC);
CREATE INDEX IF NOT EXISTS INDEX_OF_EU_DEATHMATCH_BOT_KILLS ON EU_DEATHMATCH_RANKING(SEASON_ID, BOT_KILLS DESC);
CREATE INDEX IF NOT EXISTS INDEX_OF_EU_DEATHMATCH_ELO ON EU_DEATHMATCH_RANKING(SEASON_ID, ELO DESC);

CREATE TABLE IF NOT EXISTS EU_CLAN_RANKING (
    TAG TEXT NOT NULL,
    SEASON_ID TEXT NOT NULL,
    NAME TEXT NOT NULL,
    ELO_ADDEND REAL DEFAULT 0,
    ELO_SUBTRAHEND REAL DEFAULT 0,
    ELO REAL DEFAULT 1000,
    LOGS TEXT DEFAULT '',
    PRIMARY KEY (TAG, SEASON_ID)
);

CREATE INDEX IF NOT EXISTS INDEX_OF_EU_CLAN_ELO ON EU_CLAN_RANKING(SEASON_ID, ELO DESC);

