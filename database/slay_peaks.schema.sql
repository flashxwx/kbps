CREATE TABLE IF NOT EXISTS EU_PEAKS (
    TIMESTAMP INTEGER PRIMARY KEY,
    PLAYER_COUNT INTEGER NOT NULL
) WITHOUT ROWID;

CREATE INDEX IF NOT EXISTS peaks_index ON EU_PEAKS(TIMESTAMP, PLAYER_COUNT);

