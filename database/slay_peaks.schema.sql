    TIMESTAMP INTEGER PRIMARY KEY,
    PLAYER_COUNT INTEGER NOT NULL
) WITHOUT ROWID;

CREATE INDEX IF NOT EXISTS peaks_index ON AM_PEAKS(TIMESTAMP, PLAYER_COUNT);

